let currentCurrency = localStorage.getItem('rcf_currency') || 'CAD';
let currentLang = localStorage.getItem('rcf_language') || 'en';

function setCurrency(curr) {
    if (!currencyRates[curr]) curr = 'CAD';
    currentCurrency = curr;
    localStorage.setItem('rcf_currency', curr);

    const cData = currencyRates[curr];
    const amountBtns = document.querySelectorAll('.donation-amount-btn');
    if (amountBtns.length >= 5) {
        cData.presets.forEach((val, idx) => {
            if (amountBtns[idx]) {
                amountBtns[idx].dataset.amount = val;
                amountBtns[idx].textContent = `${cData.symbol} ${val.toLocaleString()}`;
            }
        });
    }

    // Update active currency button state
    document.querySelectorAll('.currency-btn').forEach(btn => {
        btn.classList.remove('bg-white', 'text-slate-900', 'shadow-xs', 'font-black', 'bg-transparent', 'text-white/75', 'hover:text-white', 'font-medium', 'bg-primary', 'text-white', 'text-slate-700', 'hover:bg-slate-100', 'text-white/70');
        if (btn.dataset.currency === curr) {
            btn.classList.add('bg-white', 'text-slate-900', 'shadow-xs', 'font-black');
        } else {
            btn.classList.add('bg-transparent', 'text-white/75', 'hover:text-white', 'font-medium');
        }
    });

    // Update current selected amount display
    const customInput = document.getElementById('customAmountInput');
    const selectedDisplay = document.getElementById('selectedAmountDisplay');
    if (customInput && selectedDisplay) {
        const val = customInput.value || cData.presets[1];
        selectedDisplay.textContent = `${cData.symbol} ${Number(val).toLocaleString()}`;
    }
}

function setLanguage(lang) {
    if (!i18nData[lang]) lang = 'en';
    currentLang = lang;
    localStorage.setItem('rcf_language', lang);

    document.documentElement.lang = lang;

    if (lang === 'en') {
        document.body.classList.remove('font-bangla');
        document.body.classList.add('font-sans');
    } else {
        document.body.classList.remove('font-sans');
        document.body.classList.add('font-bangla');
    }

    // Replace text in all elements with data-i18n
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.dataset.i18n;
        if (i18nData[lang] && i18nData[lang][key] !== undefined) {
            if (i18nData[lang][key].includes('<')) {
                el.innerHTML = i18nData[lang][key];
            } else {
                el.textContent = i18nData[lang][key];
            }
        }
    });

    // Update Toggle Buttons active styling
    document.querySelectorAll('.lang-btn, .nav-lang-btn').forEach(btn => {
        btn.classList.remove('bg-white', 'text-slate-900', 'shadow-xs', 'font-black', 'text-white/80', 'hover:text-white', 'text-slate-600', 'bg-transparent');
        if (btn.dataset.lang === lang) {
            btn.classList.add('bg-white', 'text-slate-900', 'shadow-xs', 'font-black');
        } else {
            btn.classList.add('bg-transparent', 'text-white/80', 'hover:text-white');
        }
    });
}

window.switchLanguage = function(lang) {
    setLanguage(lang);
};

window.switchCurrency = function(curr) {
    setCurrency(curr);
};

document.addEventListener('DOMContentLoaded', () => {
    setLanguage(currentLang);
    setCurrency(currentCurrency);

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            const chosen = e.currentTarget.dataset.lang;
            if (chosen) setLanguage(chosen);
        });
    });

    document.querySelectorAll('.currency-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            const chosen = e.currentTarget.dataset.currency;
            if (chosen) setCurrency(chosen);
        });
    });
});
